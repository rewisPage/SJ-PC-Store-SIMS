-- 1. GLOBAL STORE SETTINGS (Prevents hardcoding)
CREATE TABLE STORE_SETTINGS (
    StoreID INT PRIMARY KEY,
    StoreName VARCHAR(100),
    Address VARCHAR(255),
    ContactNumber VARCHAR(20),
    TIN VARCHAR(20),
    LogoPath VARCHAR(MAX)
);

-- 2. PROCUREMENT HEADER
CREATE TABLE PROCUREMENT (
    PO_Number VARCHAR(50) PRIMARY KEY,
    SupplierID VARCHAR(20) FOREIGN KEY REFERENCES SUPPLIER(SupplierID),
    OrderDate DATETIME DEFAULT GETDATE(),
    ExpectedDate DATETIME,
    Status VARCHAR(20) DEFAULT 'Draft', -- Draft, Pending Approval, Ordered, Received, Completed, Cancelled
    CreatedBy VARCHAR(20) FOREIGN KEY REFERENCES [USER](UserID),
    CreatedOn DATETIME DEFAULT GETDATE(),
    ModifiedBy VARCHAR(20) FOREIGN KEY REFERENCES [USER](UserID),
    ModifiedOn DATETIME,
    Remarks VARCHAR(MAX),
    SubTotal DECIMAL(12,2),
    Discount DECIMAL(12,2), -- Added for Zoho-style discount
    Tax DECIMAL(12,2),
    GrandTotal DECIMAL(12,2)
);

-- 3. PROCUREMENT ITEMS
CREATE TABLE PROCUREMENT_ITEM (
    ItemID INT IDENTITY(1,1) PRIMARY KEY,
    PO_Number VARCHAR(50) FOREIGN KEY REFERENCES PROCUREMENT(PO_Number),
    ItemCode VARCHAR(50) FOREIGN KEY REFERENCES ITEM_MASTER(ItemCode),
    Quantity INT NOT NULL,
    UnitPrice DECIMAL(12,2)
);

-- 4. PROCUREMENT INVOICE (For 3-Way Matching)
CREATE TABLE PROCUREMENT_INVOICE (
    InvoiceNumber VARCHAR(50) PRIMARY KEY,
    PO_Number VARCHAR(50) FOREIGN KEY REFERENCES PROCUREMENT(PO_Number),
    InvoiceDate DATETIME,
    InvoiceAmount DECIMAL(12,2),
    InvoiceFilePath VARCHAR(MAX)
);

CREATE TABLE ATTACHMENTS (
    AttachmentID INT IDENTITY(1,1) PRIMARY KEY,
    PO_Number VARCHAR(50) NOT NULL,
    FileName NVARCHAR(255) NOT NULL,
    FilePath NVARCHAR(500) NOT NULL,
    UploadedBy NVARCHAR(100) NOT NULL,
    UploadedDate DATETIME DEFAULT GETDATE(),
    CONSTRAINT FK_Attachments_PO FOREIGN KEY (PO_Number) REFERENCES PROCUREMENT(PO_Number)
);

